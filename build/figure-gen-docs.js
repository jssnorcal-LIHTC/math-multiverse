const SCHEMATIC_LAYOUTS = ['flow-lr', 'flow-tb', 'grid', 'plan'];

function renderSchematic(dataTable, accentColor) {
  const dt = dataTable || {};
  requireType(dt, 'schematic');
  const accent = accentColor || DEFAULT_ACCENT;

  const nodes = Array.isArray(dt.nodes) ? dt.nodes : [];
  if (!nodes.length) refuse('schematic: no nodes, so there is nothing to draw');
  const edges = Array.isArray(dt.edges) ? dt.edges : [];
  const layout = dt.layout === undefined ? 'flow-lr' : dt.layout;
  if (SCHEMATIC_LAYOUTS.indexOf(layout) === -1) {
    refuse(`schematic: layout ${JSON.stringify(layout)} is not one of ${JSON.stringify(SCHEMATIC_LAYOUTS)}`);
  }

  const byId = new Map();
  nodes.forEach((nd, i) => {
    if (!nd || typeof nd.id !== 'string' || !nd.id) refuse(`schematic: node ${i} has no id`);
    if (typeof nd.label !== 'string' || !nd.label) refuse(`schematic: node ${JSON.stringify(nd.id)} has no label`);
    if (byId.has(nd.id)) refuse(`schematic: node id ${JSON.stringify(nd.id)} appears twice`);
    byId.set(nd.id, nd);
  });
  edges.forEach((e, i) => {
    if (!e || !byId.has(e.from)) refuse(`schematic: edge ${i} starts at ${JSON.stringify(e && e.from)}, which is not a node`);
    if (!byId.has(e.to)) refuse(`schematic: edge ${i} ends at ${JSON.stringify(e.to)}, which is not a node`);
  });

  const bodyTop = dt.title ? 78 : PAD;
  const bodyH = VB_H - PAD - bodyTop;
  const bodyW = VB_W - 2 * PAD;

  // Node size from the label, wrapped to at most two lines so a long transcribed phrase stays whole.
  // How wide a node may be depends on what is BESIDE it, which depends on the layout. A single
  // bodyW/3 for everything was wrong twice over: in flow-tb the nodes stack vertically and have no
  // horizontal neighbour at all, and in plan they are placed by authored x/y rather than packed into
  // columns. The real invariant is that no two boxes overlap, and that is checked after placement.
  const cellW = layout === 'flow-lr' ? bodyW / nodes.length
    : layout === 'grid' ? bodyW / Math.ceil(Math.sqrt(nodes.length))
      : layout === 'flow-tb' ? bodyW
        : bodyW / 2;
  const maxTextW = Math.max(80, cellW - 34);
  const boxes = nodes.map((nd) => {
    const wrapped = wrapToWidth(nd.label, TICK_FONT, maxTextW, 2);
    // A wrapped line wider than the cell means the boxes overlap. keyBlock already refuses in
    // this situation; the schematic used to draw the overlap and say nothing.
    wrapped.forEach((ln) => fitText(ln, TICK_FONT, maxTextW, `schematic node ${JSON.stringify(nd.id)}`));
    const tw = wrapped.reduce((m, s) => Math.max(m, estimateTextWidth(s, TICK_FONT)), 0);
    return {
      node: nd,
      lines: wrapped,
      w: Math.ceil(tw) + NODE_PAD_X * 2,
      h: wrapped.length * NODE_LINE_H + 16,
    };
  });

  boxes.forEach((b, i) => {
    if (layout === 'plan') {
      const px = typeof b.node.x === 'number' ? b.node.x : 50;
      const py = typeof b.node.y === 'number' ? b.node.y : 50;
      b.cx = PAD + (px / 100) * bodyW;
      b.cy = bodyTop + (py / 100) * bodyH;
    } else if (layout === 'flow-lr') {
      b.cx = PAD + cellW * (i + 0.5);
      b.cy = bodyTop + bodyH / 2;
    } else if (layout === 'flow-tb') {
      b.cx = VB_W / 2;
      b.cy = bodyTop + (bodyH / nodes.length) * (i + 0.5);
    } else {
      const cols = Math.ceil(Math.sqrt(nodes.length));
      const rows = Math.ceil(nodes.length / cols);
      b.cx = PAD + cellW * ((i % cols) + 0.5);
      b.cy = bodyTop + (bodyH / rows) * (Math.floor(i / cols) + 0.5);
    }
    // Keep every box wholly on the canvas whatever the authored coordinates say.
    b.cx = Math.min(VB_W - PAD - b.w / 2, Math.max(PAD + b.w / 2, b.cx));
    b.cy = Math.min(VB_H - PAD - b.h / 2, Math.max(bodyTop + b.h / 2, b.cy));
  });

  // THE REAL INVARIANT: no two node boxes may overlap. A width heuristic only approximates this, and
  // it approximated it badly in both directions -- refusing a wide node with nothing beside it, and
  // (before any check existed) drawing two boxes on top of each other in a plan layout without a
  // word. Measured on the FINAL placed geometry, after the on-canvas clamp.
  for (let i = 0; i < boxes.length; i++) {
    for (let j = i + 1; j < boxes.length; j++) {
      const a = boxes[i], b = boxes[j];
      const overlapX = Math.abs(a.cx - b.cx) < (a.w + b.w) / 2 - 1;
      const overlapY = Math.abs(a.cy - b.cy) < (a.h + b.h) / 2 - 1;
      if (overlapX && overlapY) {
        refuse(`schematic: nodes ${JSON.stringify(a.node.id)} and ${JSON.stringify(b.node.id)} overlap `
          + `in layout ${JSON.stringify(layout)}; move them apart or shorten a label`);
      }
    }
  }

  const boxById = new Map(boxes.map((b) => [b.node.id, b]));
  const out = head(dt.title);
  out.push(`<g data-layout="${esc(layout)}"></g>`);

  // Edges under the nodes, so a line never crosses a label.
  //
  // THE ENDPOINTS ARE A RAY-BOX INTERSECTION, not an approximation. The previous version took
  // `Math.min` of a half-width term and a half-height term, which is right only for a square
  // approached along a diagonal: a wide box approached from below was cut short by its half-HEIGHT
  // and the arrow stopped in mid-air pointing at nothing, while a tall one was overshot. Both were
  // visible in the shipped Night Rounds plans.
  const boxExit = (bx, dxu, dyu) => {
    const hw = bx.w / 2, hh = bx.h / 2;
    const tx = dxu === 0 ? Infinity : hw / Math.abs(dxu);
    const ty = dyu === 0 ? Infinity : hh / Math.abs(dyu);
    const t = Math.min(tx, ty);
    return { x: bx.cx + dxu * t, y: bx.cy + dyu * t };
  };

  // EVERY connector is measured before ANY label is placed. A label has to clear all of them, not
  // just its own: on the Fence Nine plan the unlabelled fence-to-creek diagonal was drawn after the
  // panel-six label and painted straight through the word "April", so the one connector visibly
  // touching the date was the connector the item said carried no label at all. That made a second
  // pairing defensible and the match item had two right answers. The rule the box test already
  // stated -- clear EVERYTHING, not merely the thing you belong to -- now covers connectors too.
  const segs = edges.map((e) => {
    const a = boxById.get(e.from), b = boxById.get(e.to);
    const dx = b.cx - a.cx, dy = b.cy - a.cy;
    const len = Math.sqrt(dx * dx + dy * dy) || 1;
    const ux = dx / len, uy = dy / len;
    const GAP = 6;
    const pa = boxExit(a, ux, uy), pb = boxExit(b, -ux, -uy);
    return {
      e, dx, dy, ux, uy,
      x1: pa.x + ux * GAP, y1: pa.y + uy * GAP,
      x2: pb.x - ux * GAP, y2: pb.y - uy * GAP,
    };
  });

  segs.forEach((sg) => {
    out.push(line(sg.x1, sg.y1, sg.x2, sg.y2, PLOT_GRID, 2));
    if (sg.e.style !== 'line') out.push(arrowHead(sg.x2, sg.y2, sg.dx, sg.dy, accent));
  });

  // AND EVERY LABEL MUST CLEAR EVERY OTHER LABEL. Third step of the same rule, found the same way
  // as the first two -- by looking at the picture rather than at the exit code. A plan with an
  // arrow arriving horizontally and another arriving vertically at the same node put "The badge
  // reads green" and "straight down" on the same few square centimetres, printing one through the
  // other, and the renderer accepted it: `clears` tested boxes and connectors and nothing else, so
  // two labels could occupy the identical rectangle and still pass. Placed labels now join the
  // test, so a drawing whose words collide is REFUSED instead of shipped.
  const placedLabels = [];

  segs.forEach((sg) => {
    const e = sg.e;
    const { x1, y1, x2, y2, ux, uy } = sg;

    if (e.label) {
      // THE LABEL MUST CLEAR EVERY BOX, not merely the line it belongs to. Placing it at the edge
      // midpoint with a fixed lift printed "was already eating" straight through "the feeding
      // shelf" and left "pressed against" half under a box border. The midpoint of the VISIBLE
      // segment is outside both endpoints' boxes by construction, but it can still land on a THIRD
      // box, so each candidate offset is tested against every box and the first clear one wins.
      fitText(e.label, NOTE_FONT, VB_W - 2 * PAD, 'schematic edge label');
      const w = estimateTextWidth(e.label, NOTE_FONT);
      const mx = (x1 + x2) / 2, my = (y1 + y2) / 2;
      // Perpendicular to the edge, so the label sits beside the connector rather than on it.
      const px = -uy, py = ux;
      const step = NOTE_FONT * 0.8 + 8;
      const clears = (cx, cy) => {
        const l = cx - w / 2, r = cx + w / 2, t = cy - NOTE_FONT * 0.8, bt = cy + NOTE_FONT * 0.25;
        if (l < PAD || r > VB_W - PAD || t < 0 || bt > VB_H) return false;
        if (boxes.some((bx) => Math.abs(bx.cx - cx) < bx.w / 2 + w / 2 - 2
          && Math.abs(bx.cy - cy) < bx.h / 2 + NOTE_FONT * 0.6 - 2)) return false;
        // AND it must clear EVERY CONNECTOR, its own included. A perpendicular offset slides a
        // label sideways, but a label is usually wider than the offset, so on a vertical edge the
        // line went straight through the middle of the words. Sampled along each segment, which
        // handles every angle without a special case per direction.
        for (const other of segs) {
          for (let i = 0; i <= 32; i++) {
            const sxp = other.x1 + (other.x2 - other.x1) * (i / 32);
            const syp = other.y1 + (other.y2 - other.y1) * (i / 32);
            if (sxp > l - 3 && sxp < r + 3 && syp > t - 3 && syp < bt + 3) return false;
          }
        }
        // AND every label already placed. Rect overlap, with the same 2px tolerance the box test
        // uses so two labels may sit shoulder to shoulder but never share ink.
        for (const p of placedLabels) {
          if (l < p.r - 2 && r > p.l + 2 && t < p.bt - 2 && bt > p.t + 2) return false;
        }
        return true;
      };
      let placed = null;
      for (let k = 1; k <= 4 && !placed; k++) {
        for (const s of [1, -1]) {
          const cx = mx + px * step * k, cy = my + py * step * k;
          if (clears(cx + 0, cy + 0)) { placed = { cx, cy }; break; }
          const cx2 = mx - px * step * k, cy2 = my - py * step * k;
          if (s === -1 && clears(cx2, cy2)) { placed = { cx: cx2, cy: cy2 }; break; }
        }
      }
      if (!placed) {
        refuse(`schematic: the label ${JSON.stringify(e.label)} on the edge ${JSON.stringify(e.from)} -> `
          + `${JSON.stringify(e.to)} cannot be placed without covering a node or crossing a connector; `
          + 'shorten it, move the nodes apart, or carry the detail in the caption');
      }
      placedLabels.push({
        l: placed.cx - w / 2, r: placed.cx + w / 2,
        t: placed.cy - NOTE_FONT * 0.8, bt: placed.cy + NOTE_FONT * 0.25,
      });
      out.push(text(placed.cx, placed.cy, NOTE_FONT, e.label, { anchor: 'middle', opacity: '0.82' }));
    }
  });

  boxes.forEach((b) => {
    const x = b.cx - b.w / 2, y = b.cy - b.h / 2;
    const round = b.node.shape === 'round';
    out.push(rect(x, y, b.w, b.h, {
      fill: CARD_FILL, stroke: round ? accent : PLOT_GRID, strokeWidth: 2,
      rx: round ? b.h / 2 : 4, extra: `data-shape="${esc(round ? 'round' : 'box')}"`,
    }));
    const ty0 = b.cy - (b.lines.length - 1) * NODE_LINE_H / 2 + 7;
    out.push(textLines(b.cx, ty0, TICK_FONT, b.lines, { anchor: 'middle', lineH: NODE_LINE_H }));
  });

  return finish(out);
}

