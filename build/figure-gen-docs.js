function renderRoute(dataTable, accentColor) {
  const dt = dataTable || {};
  requireType(dt, 'route');
  const accent = accentColor || DEFAULT_ACCENT;

  const stops = Array.isArray(dt.stops) ? dt.stops : [];
  if (!stops.length) refuse('route: no stops, so there is no route to draw');
  stops.forEach((s, i) => {
    if (!s || typeof s.label !== 'string' || !s.label) refuse(`route: stop ${i} has no label`);
    if (typeof s.n !== 'number') refuse(`route: stop ${JSON.stringify(s.label)} has no number`);
  });
  const path = dt.path === undefined ? 'loop' : dt.path;
  if (path !== 'loop' && path !== 'line') {
    refuse(`route: path ${JSON.stringify(path)} is neither "loop" nor "line"`);
  }

  const out = head(dt.title);
  const bodyTop = dt.title ? 78 : PAD;

  if (path === 'loop') {
    // Direct labels around an ellipse, sized so the widest label still clears the canvas edge. If
    // that leaves no ellipse worth drawing, the numbered key is used instead -- measured, not
    // guessed, so the choice is deterministic.
    const widest = stops.reduce((m, s) => Math.max(m, estimateTextWidth(s.label, LABEL_FONT)), 0);
    const cx = VB_W / 2, cy = bodyTop + (VB_H - PAD - bodyTop) / 2;
    const rx = Math.min(190, VB_W / 2 - PAD - widest - 18);
    const ry = Math.min(120, (VB_H - PAD - bodyTop) / 2 - 26);
    if (rx >= 70) {
      const pts = stops.map((s, i) => {
        const a = -Math.PI / 2 + (i * 2 * Math.PI) / stops.length;
        return { x: cx + rx * Math.cos(a), y: cy + ry * Math.sin(a), a: a, s: s };
      });
      const poly = pts.map((p) => `${n2(p.x)},${n2(p.y)}`).join(' ');
      out.push(`<polygon points="${poly}" fill="none" stroke="${PLOT_GRID}" stroke-width="2" data-path="loop" />`);
      pts.forEach((p, i) => {
        out.push(circle(p.x, p.y, 13, { fill: accent }));
        out.push(text(p.x, p.y + 7, NOTE_FONT, String(p.s.n), { anchor: 'middle', fill: '#0f1218' }));
        const right = Math.cos(p.a) > 0.2, left = Math.cos(p.a) < -0.2;
        const anchor = right ? 'start' : left ? 'end' : 'middle';
        const lx = p.x + (right ? 20 : left ? -20 : 0);
        const ly = p.y + (Math.abs(Math.cos(p.a)) <= 0.2 ? (Math.sin(p.a) > 0 ? 34 : -22) : 7);
        out.push(text(lx, ly, LABEL_FONT, p.s.label, { anchor: anchor }));
        if (p.s.note) {
          out.push(text(lx, ly + 22, NOTE_FONT, p.s.note, { anchor: anchor, fill: accent }));
        }
      });
      return finish(out);
    }
  }

  // A line route, and the fallback for a loop whose labels will not fit around it.
  const y = bodyTop + 46;
  const AX_L = PAD + 14, AX_R = VB_W - PAD - 14;
  out.push(line(AX_L, hp(y), AX_R, hp(y), PLOT_GRID, 2, { extra: `data-path="${esc(path)}"` }));
  stops.forEach((s, i) => {
    const x = stops.length === 1 ? (AX_L + AX_R) / 2 : AX_L + (i / (stops.length - 1)) * (AX_R - AX_L);
    out.push(circle(x, y, 13, { fill: accent }));
    out.push(text(x, y + 7, NOTE_FONT, String(s.n), { anchor: 'middle', fill: '#0f1218' }));
  });
  const entries = stops.map((s) => ({ n: s.n, lead: s.note || '', label: s.label }));
  keyBlock(entries, y + 34, accent).out.forEach((line_) => out.push(line_));
  return finish(out);
}

