'use strict';
// figure-gen-docs.js -- the four DOCUMENT renderers that let a reading pack carry built graphics:
// renderTimeline, renderFacsimile, renderSchematic, renderRoute, dispatched by genSvgDoc().
//
// WHY THESE EXIST. build/figure-gen.js renders charts, and a chart is the wrong shape for almost
// every illustration a grade-6 reading passage wants: a witness table, a diet card, a floor plan,
// an evening-rounds route, a night's sequence of events. The three ELA packs carry 432 items and
// zero figures because nothing here could draw a document. These four can, and because every one
// of them is generated FROM A COMMITTED dataTable, every ELA figure stays byte-derivable
// (tests/figure-derive.js), blind-certifiable (the ledger dumps the dataTable in place of the
// image) and checkable for fidelity to its passage (tests/figure-fidelity.js asserts every label
// is a verbatim substring of the passage it illustrates). Transcription is the control.
//
// EVERY RENDERER IS PURE: (dataTable, accent) -> one SVG string. No Date, no Math.random, no
// object-key iteration, no I/O, and the dataTable it is handed is never mutated. Same inputs ->
// byte-identical output, forever. That is what lets a committed .svg be an expected value.
//
// EVERY RENDERER REFUSES rather than degrades, exactly as genSvg does: an edge to a node that does
// not exist, an event on an undeclared track, a table too tall for its card, a timeline whose times
// do not run forwards. A figure that quietly drops half its data is worse than no figure, because
// the item written against it would then be unanswerable and the blind pass would agree with the
// author for the wrong reason.
//
// DEPENDENCY DIRECTION IS LOAD-BEARING: this file requires ONLY ./figure-tokens.js. It must never
// require ./figure-gen.js, which requires THIS file for dispatch; figure-gen.js assigns its
// module.exports last, so a cycle would hand this module an empty {} and every token would be
// undefined -- invisibly, because the fixtures would be generated by that same broken code.

const T = require('./figure-tokens.js');

const {
  VB_W, VB_H, INK, PLOT_GRID, RULE, CARD_FILL, HEADER_STROKE, STAMP_STROKE, HATCH_STROKE,
  REDACTION_FILL, TITLE_FONT, LABEL_FONT, TICK_FONT, NOTE_FONT, DEFAULT_ACCENT,
  n2, esc, hp, estimateTextWidth, refuse, wrapToWidth, truncateToWidth, svgRootLines,
} = T;

const DOC_TYPES = ['timeline', 'facsimile', 'schematic', 'route'];

const PAD = 40;             // outer margin on every side
const TITLE_Y = 44;         // baseline of a figure's title row
const ROW_H = 26;           // one key/table row
const NODE_PAD_X = 16;      // horizontal padding inside a schematic node
const NODE_LINE_H = 24;     // one wrapped line inside a schematic node

// --------------------------------------------------------------------------------------------
// small emitters -- every attribute in a fixed literal order, every number through n2()
// --------------------------------------------------------------------------------------------

function text(x, y, size, content, opts) {
  const o = opts || {};
  let s = `<text x="${n2(x)}" y="${n2(y)}" font-size="${size}" fill="${o.fill || INK}"`;
  if (o.anchor) s += ` text-anchor="${o.anchor}"`;
  if (o.opacity !== undefined) s += ` fill-opacity="${o.opacity}"`;
  if (o.extra) s += ' ' + o.extra;
  return s + `>${esc(content)}</text>`;
}

// A wrapped label, emitted as ONE <text> element with a <tspan> per line rather than one <text> per
// line. That distinction is load-bearing, not cosmetic: tests/figure-fidelity.js asserts every
// transcribed string appears verbatim in the figure, and it reads the collapsed text content of a
// single text node. Split across separate <text> elements, "the tortoise yard" exists nowhere in the
// document as a whole string and the gate would be right to reject a figure that does draw it.
// The tspans are joined by a space so the collapsed content reads as the original phrase.
function textLines(x, y, size, lines, opts) {
  const o = opts || {};
  let s = `<text x="${n2(x)}" y="${n2(y)}" font-size="${size}" fill="${o.fill || INK}"`;
  if (o.anchor) s += ` text-anchor="${o.anchor}"`;
  if (o.opacity !== undefined) s += ` fill-opacity="${o.opacity}"`;
  if (o.extra) s += ' ' + o.extra;
  s += '>';
  s += lines.map((ln, i) => `<tspan x="${n2(x)}" dy="${i === 0 ? 0 : (o.lineH || 22)}">${esc(ln)}</tspan>`).join(' ');
  return s + '</text>';
}

function line(x1, y1, x2, y2, stroke, width, opts) {
  const o = opts || {};
  let s = `<line x1="${n2(x1)}" y1="${n2(y1)}" x2="${n2(x2)}" y2="${n2(y2)}" stroke="${stroke}" stroke-width="${width || 1}"`;
  if (o.dash) s += ` stroke-dasharray="${o.dash}"`;
  if (o.extra) s += ' ' + o.extra;
  return s + ' />';
}

function rect(x, y, w, h, opts) {
  const o = opts || {};
  let s = `<rect x="${n2(x)}" y="${n2(y)}" width="${n2(w)}" height="${n2(h)}"`;
  s += ` fill="${o.fill || 'none'}"`;
  if (o.stroke) s += ` stroke="${o.stroke}" stroke-width="${o.strokeWidth || 1}"`;
  if (o.rx) s += ` rx="${n2(o.rx)}"`;
  if (o.dash) s += ` stroke-dasharray="${o.dash}"`;
  if (o.extra) s += ' ' + o.extra;
  return s + ' />';
}

function circle(cx, cy, r, opts) {
  const o = opts || {};
  let s = `<circle cx="${n2(cx)}" cy="${n2(cy)}" r="${n2(r)}"`;
  s += ` fill="${o.fill || 'none'}"`;
  if (o.stroke) s += ` stroke="${o.stroke}" stroke-width="${o.strokeWidth || 1}"`;
  if (o.dash) s += ` stroke-dasharray="${o.dash}"`;
  if (o.extra) s += ' ' + o.extra;
  return s + ' />';
}

function polygon(points, fill) {
  return `<polygon points="${points}" fill="${fill}" />`;
}

// A hatched band, drawn as explicit diagonal strokes rather than a <pattern> in <defs>. Every other
// generator in this repo emits a flat element list with no defs and no ids; keeping that shape means
// nothing here depends on id scoping when the same SVG is inlined, thumbnailed and lightboxed.
function hatchBand(x, y, w, h, label) {
  const out = [rect(x, y, w, h, { stroke: HATCH_STROKE, extra: `data-gap="${esc(label || '')}"` })];
  const step = 12;
  // Deterministic: a fixed step walked from a fixed origin, clipped by construction rather than by
  // a clip-path, so the same band is the same bytes every time.
  for (let o = step; o < w + h; o += step) {
    let x1 = x + o, y1 = y, x2 = x, y2 = y + o;
    if (x1 > x + w) { y1 += x1 - (x + w); x1 = x + w; }
    if (y2 > y + h) { x2 += y2 - (y + h); y2 = y + h; }
    if (x1 <= x2 || y1 >= y2) continue;
    out.push(line(x1, y1, x2, y2, HATCH_STROKE, 1));
  }
  return out;
}

function arrowHead(x, y, dx, dy, accent) {
  // Unit direction, then a 10x7 head. Math.hypot is deterministic for finite inputs.
  const len = Math.sqrt(dx * dx + dy * dy) || 1;
  const ux = dx / len, uy = dy / len;
  const px = -uy, py = ux;
  const tipX = x, tipY = y;
  const bx = x - ux * 11, by = y - uy * 11;
  const pts = [
    `${n2(tipX)},${n2(tipY)}`,
    `${n2(bx + px * 5)},${n2(by + py * 5)}`,
    `${n2(bx - px * 5)},${n2(by - py * 5)}`,
  ].join(' ');
  return polygon(pts, accent);
}

function finish(out) {
  out.push('</svg>');
  return out.join('\n') + '\n';
}

function head(title) {
  const out = svgRootLines();
  if (title) out.push(text(PAD, TITLE_Y, TITLE_FONT, title));
  return out;
}

function requireType(dt, want) {
  if (!dt || typeof dt !== 'object') refuse(`${want}: no dataTable was supplied`);
  if (dt.type !== want) {
    refuse(`${want}: dataTable.type is ${JSON.stringify(dt.type)}, not "${want}"`);
  }
}

// A numbered key: the layout the timeline uses for its event labels, and the one a line route falls
// back to. ONE COLUMN is strongly preferred, because the full 720px width is what lets a transcribed
// label stay whole; the row height shrinks first, and a second column is used only when even the
// tightest single column will not fit the canvas.
//
// It REFUSES rather than truncates. A truncated label is one tests/figure-fidelity.js can no longer
// find verbatim in the figure, and silently shortening a transcription is the exact failure this
// program's whole design exists to prevent.
const KEY_ROW_MIN = 20;

function keyBlock(entries, top, accent) {
  const out = [];
  const availH = VB_H - PAD - top;
  const gutter = 24;

  let cols = 1;
  let rowH = Math.min(ROW_H, Math.floor(availH / entries.length));
  if (rowH < KEY_ROW_MIN) {
    cols = 2;
    rowH = Math.min(ROW_H, Math.floor(availH / Math.ceil(entries.length / 2)));
    if (rowH < KEY_ROW_MIN) {
      refuse(`key: ${entries.length} entries do not fit in ${Math.floor(availH)}px even in two columns; `
        + 'split the figure or shorten the sequence');
    }
  }
  const colW = (VB_W - 2 * PAD - (cols - 1) * gutter) / cols;
  const perCol = Math.ceil(entries.length / cols);

  const numW = 30;
  const leadFont = cols === 1 ? TICK_FONT : NOTE_FONT;
  const labelFont = cols === 1 ? LABEL_FONT : TICK_FONT;
  const leadW = entries.reduce((m, e) => Math.max(m, estimateTextWidth(e.lead || '', leadFont)), 0);
  const labelX0 = numW + (leadW ? Math.ceil(leadW) + 14 : 0);
  const room = colW - labelX0;

  entries.forEach((e) => {
    if (estimateTextWidth(e.label, labelFont) > room) {
      refuse(`key: "${e.label}" needs ${Math.ceil(estimateTextWidth(e.label, labelFont))}px but only `
        + `${Math.floor(room)}px remain beside its number and time; shorten the transcription or `
        + 'move the detail into the caption');
    }
  });

  entries.forEach((e, i) => {
    const col = Math.floor(i / perCol);
    const row = i % perCol;
    const x = PAD + col * (colW + gutter);
    const y = top + row * rowH + NOTE_FONT;
    out.push(text(x + numW - 8, y, NOTE_FONT, e.n + '.', { anchor: 'end', fill: accent }));
    if (e.lead) out.push(text(x + numW, y, leadFont, e.lead, { opacity: '0.82' }));
    out.push(text(x + labelX0, y, labelFont, e.label, e.mark ? { extra: `data-kind="${e.mark}"` } : undefined));
  });
  return { out };
}

