function renderFacsimile(dataTable, accentColor) {
  const dt = dataTable || {};
  requireType(dt, 'facsimile');
  const accent = accentColor || DEFAULT_ACCENT;

  const header = Array.isArray(dt.header) ? dt.header : [];
  const lines = Array.isArray(dt.lines) ? dt.lines : [];
  const columns = Array.isArray(dt.columns) ? dt.columns : [];
  if (!header.length && !lines.length && !columns.length) {
    refuse('facsimile: no header, no lines and no columns, so there is no document to draw');
  }

  const CX = 56, CY = 34, CW = VB_W - 2 * CX, CH = VB_H - CY - 30;
  const out = svgRootLines();
  out.push(rect(CX, CY, CW, CH, { fill: CARD_FILL, stroke: RULE, rx: 6 }));

  const innerX = CX + 22;
  const innerW = CW - 44;
  let y = CY + 16;

  if (dt.title) {
    y += TITLE_FONT;
    out.push(text(innerX, y, TITLE_FONT, dt.title));
    y += 12;
    // THE MASTHEAD RULE STOPS AT THE STAMP. Drawn full width it ran straight through the rotated
    // Corvid Systems stamp -- the stamp box spans y 52..92 and the rule sits at y 88.5 -- so the
    // crossing line read as part of the stamp and blurred where the masthead ended and the stamp
    // began. It was the only place in the pack where a line ran through a drawn shape. The stamp's
    // own left edge is recomputed here from the same expression the stamp block uses below, so the
    // two cannot drift; the 16px gap matches the clearance the stamp already demands of the title.
    let ruleRight = CX + CW - 22;
    if (dt.stamp) {
      const sw = estimateTextWidth(dt.stamp, LABEL_FONT) + 26;
      ruleRight = Math.min(ruleRight, CX + CW - sw - 26 - 16);
    }
    out.push(line(innerX, hp(y), ruleRight, hp(y), HEADER_STROKE, 1));
    y += 10;
  }

  if (header.length) {
    const labW = header.reduce((m, h) => Math.max(m,
      estimateTextWidth((h && h.label) || '', h && h.contrast === true ? LABEL_FONT : TICK_FONT)), 0);
    header.forEach((h, i) => {
      if (!h || typeof h.value !== 'string') refuse(`facsimile: header row ${i} has no value`);
      y += LABEL_FONT + 6;
      // A CONTRAST ROW SETS BOTH HALVES AT THE SAME WEIGHT. The header block's styling teaches one
      // relation -- dim small label on the left, bright large value on the right, a field and its
      // value -- and four of Cold Signal's six document cards use it that way. The two memo cards
      // then used the SAME block for a contrast, "the same tracking tag | three different climates",
      // where the left half carries half the argument (what stayed the same) and was wearing the
      // throwaway-label treatment, with a genuine field-and-value row stacked directly beneath it
      // and nothing to tell the two apart. Marking the row `contrast: true` draws both halves alike,
      // so the block keeps ONE meaning per appearance. Rows without the flag are byte-identical.
      const contrast = h.contrast === true;
      if (h.label) {
        out.push(contrast
          ? text(innerX, y, LABEL_FONT, h.label)
          : text(innerX, y, TICK_FONT, h.label, { opacity: '0.82' }));
      }
      const hx = innerX + Math.ceil(labW) + 16;
      if (h.value === '') {
        // A FIELD PRINTED AND LEFT EMPTY, drawn as the empty rule a form actually shows. This has
        // to be DATA rather than an item's assertion: the previous attempt put the label in a box
        // and let three items say the row was blank, but `emphasis: "box"` means PRINTED CONTENT
        // BEING CALLED OUT everywhere else in this pack (the diet card's thiamine line, the witness
        // table's "None of the three witnesses saw anything at all"), so the pack's one emphasis
        // device was being read as its own opposite. An empty value draws an empty field.
        out.push(line(hx, hp(y + 5), CX + CW - 22, hp(y + 5), RULE, 1, { extra: 'data-empty-field="1"' }));
      } else {
        fitText(h.value, LABEL_FONT, (CX + CW - 22) - hx, `facsimile header[${i}].value`);
        out.push(text(hx, y, LABEL_FONT, h.value));
      }
    });
    y += 12;
    out.push(line(innerX, hp(y), CX + CW - 22, hp(y), HEADER_STROKE, 1));
    y += 6;
  }

  // A BOX SPANS ITS WHOLE RUN, not one rect per line. An author marks EVERY line of an instruction
  // `box` because the instruction wraps, and drawing one outline per line rendered the diet card's
  // two-line thiamine instruction as two stacked rectangles of different widths (425px over 604px,
  // sharing only their left edge), which reads as two separate boxed statements. The card it
  // transcribes says the opposite: "Under the fish comes a line the card sets apart inside its own
  // box" -- one box. Found by the C4 round-5 drawing lens, which read the shipped SVG rather than
  // the dataTable.
  //
  // A RUN OF ONE IS BYTE-IDENTICAL to what this drew before (top y - font, height font + 12, width
  // w + 16), so no single-line box anywhere moves; measured across all six packs, exactly one
  // figure has a run longer than one.
  const boxRunStart = new Array(lines.length).fill(-1);
  const boxRunEnd = new Array(lines.length).fill(-1);
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (!l || typeof l !== 'object' || l.emphasis !== 'box') continue;
    boxRunStart[i] = (i > 0 && boxRunStart[i - 1] !== -1) ? boxRunStart[i - 1] : i;
  }
  for (let i = 0; i < lines.length; i++) {
    if (boxRunStart[i] !== -1) boxRunEnd[boxRunStart[i]] = i;   // last write wins: the run's end
  }

  lines.forEach((l, i) => {
    if (!l || typeof l !== 'object') refuse(`facsimile: line ${i} is not an object`);
    const em = l.emphasis;
    y += LABEL_FONT + 10;
    if (em === 'blank') {
      // A FIELD PRINTED AND LEFT EMPTY: the label, then the rule where the entry would go. This is
      // DATA, not an item's assertion. The previous attempt boxed the label and let three items say
      // the row was blank, but `emphasis: "box"` means PRINTED CONTENT BEING CALLED OUT everywhere
      // else in this pack (the diet card's thiamine line, the witness table's "None of the three
      // witnesses saw anything at all"), so the pack's one emphasis device was being read as its own
      // opposite. A blank field now draws as a blank field.
      if (typeof l.text !== 'string' || !l.text) refuse(`facsimile: line ${i} is blank but has no label`);
      const lw = estimateTextWidth(l.text, LABEL_FONT);
      // 90px reserved for the rule: enough that the empty field reads as a field, not a margin.
      fitText(l.text, LABEL_FONT, innerW - 90, `facsimile line ${i} (blank field label)`);
      out.push(text(innerX, y, LABEL_FONT, l.text));
      out.push(line(innerX + lw + 14, hp(y + 5), CX + CW - 22, hp(y + 5), RULE, 1,
        { extra: 'data-empty-field="1"' }));
      return;
    }
    if (em === 'redact') {
      // A redaction draws a bar and NEVER text under it: nothing a reader could recover.
      out.push(rect(innerX, y - LABEL_FONT + 2, innerW * 0.62, LABEL_FONT + 2,
        { fill: REDACTION_FILL, extra: 'data-emphasis="redact"' }));
      return;
    }
    if (typeof l.text !== 'string' || !l.text) refuse(`facsimile: line ${i} has no text and is not a redaction`);
    // Step the size down before giving up, and REFUSE rather than truncate: a truncated line is one
    // tests/figure-fidelity.js can no longer find verbatim in the passage it was transcribed from.
    const room = innerW - 24;
    const font = estimateTextWidth(l.text, LABEL_FONT) <= room ? LABEL_FONT : TICK_FONT;
    if (estimateTextWidth(l.text, font) > room) {
      refuse(`facsimile: line ${i} "${l.text}" needs ${Math.ceil(estimateTextWidth(l.text, font))}px `
        + `but the card is ${Math.floor(room)}px wide; shorten the transcription`);
    }
    const t = { text: l.text };
    const w = estimateTextWidth(t.text, font);
    if (em === 'box') {
      // Only the FIRST line of a run draws, and it draws the whole run. Lines advance by a fixed
      // LABEL_FONT + 10 whatever their own font, so the run's extent is arithmetic, and the width
      // is the widest line in it measured at the font that line will actually render with.
      if (boxRunStart[i] === i) {
        const step = LABEL_FONT + 10;
        const end = boxRunEnd[i];
        let widest = 0;
        for (let k = i; k <= end; k++) {
          const kt = lines[k].text;
          const kf = estimateTextWidth(kt, LABEL_FONT) <= room ? LABEL_FONT : TICK_FONT;
          widest = Math.max(widest, estimateTextWidth(kt, kf));
        }
        // THE BOX MUST NOT REACH THE LINE BELOW IT. With 12px of bottom padding the outline ended at
        // y 276 while the next line's ascenders began at 274 -- a 2px OVERLAP, so on a card where a
        // red rule already means "small print", the box's lower edge read as an underline on the
        // line beneath it. Padding trimmed to 8 (descenders reach about 5px below the baseline, so
        // it still contains them) and the run is followed by 4px of extra advance, measured back to
        // 6px of clear space. Grew visible only once a box spanned TWO lines and sat mid-block.
        const top = y - font - 2;
        const bottom = y + (end - i) * step + 8;
        out.push(rect(innerX - 8, top, widest + 16, bottom - top,
          { stroke: accent, strokeWidth: 2, rx: 3, extra: 'data-emphasis="box"' }));
      }
    } else if (em === 'underline') {
      out.push(line(innerX, hp(y + 5), innerX + w, hp(y + 5), accent, 2, { extra: 'data-emphasis="underline"' }));
    }
    // A boxed run ends with a little extra air, so the outline never crowds the next line.
    if (em === 'box' && boxRunEnd[boxRunStart[i]] === i) y += 4;

    // A plain line gets NO rule. Ruling every line made a flowing newspaper paragraph render as a
    // stack of table rows, and worse, it made the gray rules almost indistinguishable from the
    // ACCENT underline that marks a disputed sentence -- which is the one thing the figure exists
    // to show. Rules now appear only where the document itself has one: under the title and under
    // the header block.
    out.push(text(innerX, y, font, t.text));
  });

  if (columns.length) {
    y += 18;
    // The label column takes a share of the width; the data columns narrow to make room, so the
    // table still fits the card rather than running off it.
    // THE STUB IS AS WIDE AS ITS LABELS, not a flat 150px. A fixed stub spent the same width on
    // "the rock" as on a long row label and took it from the DATA columns, which is what made
    // fig-l5-three-tunnels refuse row labels at all: the cell "the full life of the battery" could
    // not fit what was left. Refusing labels is not neutral -- its sister card fig-l5-three-climates
    // labels the same rows in the same position, so the leftmost column ends up meaning "which
    // attribute" on one card and "the first attribute's data, unlabelled" on the other, which is
    // the pixel review's finding. Still capped at 24% of the card so a long label cannot starve the
    // table.
    const labelColW = Array.isArray(dt.rowLabels) && dt.rowLabels.length
      ? Math.min(innerW * 0.24,
          dt.rowLabels.reduce((m, r) => Math.max(m, estimateTextWidth(String(r), TICK_FONT)), 0) + 18)
      : 0;
    const colW = (innerW - labelColW) / columns.length;
    const cellW = colW - 14;
    const rowsN = columns.reduce((m, c) => Math.max(m, (c && Array.isArray(c.rows) ? c.rows.length : 0)), 0);
    const CELL_LINE_H = 22;

    // WRAP, NEVER TRUNCATE. A truncated cell is a label tests/figure-fidelity.js can no longer find
    // verbatim in the figure, which is the one thing this whole design exists to guarantee. Two lines
    // are allowed; a cell that still will not fit is REFUSED by name, so the author shortens the
    // transcription deliberately instead of the renderer doing it silently.
    const fitOrRefuse = (s, font, where) => {
      const lines_ = wrapToWidth(String(s), font, cellW, 2);
      lines_.forEach((ln) => {
        if (estimateTextWidth(ln, font) > cellW) {
          refuse(`facsimile: ${where} "${s}" needs ${Math.ceil(estimateTextWidth(ln, font))}px but the `
            + `column is ${Math.floor(cellW)}px; use fewer columns or a shorter transcription`);
        }
      });
      return lines_;
    };

    // D17: OPTIONAL ROW LABELS. Columns were named and rows were not, so a witness table's fourth
    // row read as WHEN THE NOISE HAPPENED rather than when the account was given -- which is exactly
    // the distinction its item tests. rowLabels is a leading column, fidelity-checked like any other
    // transcription, and it narrows the data columns to make room rather than overflowing them.
    const rowLabels = Array.isArray(dt.rowLabels) ? dt.rowLabels : null;
    if (rowLabels && rowLabels.length !== rowsN) {
      refuse(`facsimile: rowLabels has ${rowLabels.length} entries but the table has ${rowsN} rows`);
    }
    const heads = columns.map((c, ci) => {
      if (!c || typeof c.heading !== 'string') refuse(`facsimile: column ${ci} has no heading`);
      return fitOrRefuse(c.heading, LABEL_FONT, `column heading`);
    });
    const cells = [];
    for (let r = 0; r < rowsN; r++) {
      cells.push(columns.map((c) => {
        const v = (c.rows || [])[r];
        if (v === undefined || v === null || v === '') return null;
        return fitOrRefuse(v, TICK_FONT, 'cell');
      }));
    }
    const headH = Math.max.apply(null, heads.map((h) => h.length)) * CELL_LINE_H + 12;
    const rowH = cells.map((row) => Math.max(1, Math.max.apply(null,
      row.map((c) => (c ? c.length : 1)))) * CELL_LINE_H + 6);
    const needed = headH + rowH.reduce((a, b) => a + b, 0) + 10;
    if (y + needed > CY + CH - 10) {
      refuse(`facsimile: ${columns.length} columns of ${rowsN} rows need ${Math.ceil(needed)}px but only `
        + `${Math.floor(CY + CH - 10 - y)}px remain under the header; shorten the table or move it to its own figure`);
    }

    const tableBottom = y + needed;
    heads.forEach((h, ci) => {
      const cx = innerX + labelColW + ci * colW;
      out.push(textLines(cx, y + LABEL_FONT, LABEL_FONT, h, { lineH: CELL_LINE_H }));
      if (ci > 0) out.push(line(hp(cx - 8), y - 6, hp(cx - 8), tableBottom - 10, RULE, 1));
    });
    const headBase = y + headH;
    out.push(line(innerX, hp(headBase), CX + CW - 22, hp(headBase), HEADER_STROKE, 1));
    let ry = headBase;
    cells.forEach((row, r) => {
      if (labelColW) {
        const lab = dt.rowLabels[r];
        if (typeof lab === 'string' && lab.trim()) {
          const wrapped = fitOrRefuse(lab, TICK_FONT, 'row label');
          out.push(textLines(innerX, ry + TICK_FONT + 4, TICK_FONT, wrapped, { lineH: CELL_LINE_H, opacity: '0.82' }));
        }
      }
      row.forEach((cell, ci) => {
        if (!cell) return;
        const cx = innerX + labelColW + ci * colW;
        out.push(textLines(cx, ry + TICK_FONT + 4, TICK_FONT, cell, { lineH: CELL_LINE_H }));
      });
      ry += rowH[r];
      if (r < cells.length - 1) out.push(line(innerX, hp(ry - 3), CX + CW - 22, hp(ry - 3), RULE, 1));
    });
    y = ry;
  }

  // A LINE AT THE FOOT OF THE PAGE IS ITS OWN THING, not a column. Cold Signal's log card needed
  // "one more line at the bottom of the page" -- the passage's own words, and the whole point of
  // the document, because Jonah adds it afterwards. Authored as a second COLUMN it became four
  // fragments of one sentence sitting on four ruled rows, each one pairing with the log entry
  // beside it, so the drawing manufactured four facts the record does not contain: that the ten
  // fourteen entry cost thirty seconds, that contacting the front desk happened on the second floor
  // landing, that the two clicks had unknown cause. Only "Thirty" was capitalised, which is the
  // tell. The shape had no way to say "a line at the foot", so the author reached for the nearest
  // thing that would render.
  //
  // Pinned to the bottom of the card, above a rule, and refused if the body reaches it -- so it
  // cannot repeat the older failure of drawing over the content it was meant to sit beneath.
  if (dt.footnote !== undefined) {
    if (typeof dt.footnote !== 'string' || !dt.footnote) refuse('facsimile: footnote must be a non-empty string');
    // It WRAPS, up to two lines. A sentence written along the foot of a page is a sentence, not a
    // field, and refusing it for length would only push an author back to the shape that caused the
    // defect. Two lines is the same ceiling the cells and node labels use.
    const wrapped = wrapToWidth(dt.footnote, TICK_FONT, innerW, 2);
    const widest = wrapped.reduce((m, s) => Math.max(m, estimateTextWidth(s, TICK_FONT)), 0);
    if (widest > innerW) {
      refuse(`facsimile footnote: ${JSON.stringify(dt.footnote)} does not fit two lines of `
        + `${Math.floor(innerW)}px; shorten the transcription or move the detail to the caption`);
    }
    const FOOT_LINE_H = 22;   // same line pitch the column cells use
    const fy = CY + CH - 22 - (wrapped.length - 1) * FOOT_LINE_H;
    if (y > fy - 22) {
      refuse(`facsimile: the footnote ${JSON.stringify(dt.footnote)} has no clear space at the foot of `
        + 'the card; drop a line or shorten the transcription');
    }
    out.push(line(innerX, hp(fy - 18), CX + CW - 22, hp(fy - 18), RULE, 1));
    out.push(textLines(innerX, fy, TICK_FONT, wrapped, { lineH: FOOT_LINE_H }));
  }

  // THE CARD MUST CONTAIN ITS CONTENTS. y has walked down the card as each block was drawn; if it
  // has passed the bottom edge, lines were painted onto the panel BEHIND the card and the last one
  // rendered outside the frame entirely. There was a fit check for the column table and none at all
  // for the ruled lines, so a long clipping simply overflowed in silence.
  if (y > CY + CH - 8) {
    refuse(`facsimile: the content runs ${Math.ceil(y - (CY + CH - 8))}px past the bottom of the card; `
      + 'drop a line or shorten the transcription');
  }

  if (dt.stamp) {
    fitText(dt.stamp, LABEL_FONT, CW - 60, 'facsimile stamp');
    const sw = estimateTextWidth(dt.stamp, LABEL_FONT) + 26;
    // THE STAMP GOES IN THE TOP-RIGHT CORNER, beside the title. Pinned to the card BOTTOM it was
    // drawn straight across the body copy of a long clipping, and a rotated stamp over text makes
    // both illegible -- the two disputed sentences the figure exists to show were the ones it
    // covered. Chasing the content downward instead just moved the collision around, because a card
    // whose lines reach the bottom has no clear space below them by definition. The top-right is
    // where a stamp goes on a real form, and the title is short and left-aligned, so the only thing
    // it can collide with is a title long enough to reach it -- which is checked, not assumed.
    const sx = CX + CW - sw - 26;
    const sy = CY + 18;
    const titleRight = dt.title ? innerX + estimateTextWidth(dt.title, TITLE_FONT) : innerX;
    if (titleRight > sx - 16) {
      refuse(`facsimile: the stamp ${JSON.stringify(dt.stamp)} would sit on the title `
        + `${JSON.stringify(dt.title)}; shorten one of them`);
    }
    const cx = sx + sw / 2, cy = sy + 20;
    out.push(`<g transform="rotate(-12 ${n2(cx)} ${n2(cy)})">`);
    out.push(rect(sx, sy, sw, 40, { stroke: STAMP_STROKE, strokeWidth: 2, rx: 4, extra: 'data-stamp="1"' }));
    out.push(text(cx, cy + 8, LABEL_FONT, dt.stamp, { anchor: 'middle', fill: accent }));
    out.push('</g>');
  }

  return finish(out);
}

