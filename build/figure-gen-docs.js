function genSvgDoc(dataTable, accentColor) {
  const dt = dataTable || {};
  switch (dt.type) {
    case 'timeline': return renderTimeline(dt, accentColor);
    case 'facsimile': return renderFacsimile(dt, accentColor);
    case 'schematic': return renderSchematic(dt, accentColor);
    case 'route': return renderRoute(dt, accentColor);
    default:
      return refuse(`genSvgDoc: dataTable.type ${JSON.stringify(dt.type)} is not one of ${JSON.stringify(DOC_TYPES)}`);
  }
}

