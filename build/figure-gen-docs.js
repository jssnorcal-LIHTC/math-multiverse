// Recognises a clock time and returns minutes past midnight, or null. Deliberately narrow: it
// accepts only what a passage actually writes, so anything else falls to the ordinal scale rather
// than being guessed at. A guessed time is a lie the reader cannot check.
function parseClock(s) {
  const m = /^\s*(\d{1,2}):(\d{2})(?::(\d{2}))?\s*(a\.m\.|p\.m\.|am|pm|A\.M\.|P\.M\.|AM|PM)?\s*$/.exec(String(s));
  if (!m) return null;
  let h = parseInt(m[1], 10);
  const min = parseInt(m[2], 10);
  const sec = m[3] ? parseInt(m[3], 10) : 0;
  if (h > 23 || min > 59 || sec > 59) return null;
  const mer = m[4] ? m[4].toLowerCase().replace(/\./g, '') : null;
  if (mer) {
    if (h > 12 || h < 1) return null;
    if (mer === 'pm' && h !== 12) h += 12;
    if (mer === 'am' && h === 12) h = 0;
  }
  return h * 60 + min + sec / 60;
}

function renderTimeline(dataTable, accentColor) {
  const dt = dataTable || {};
  requireType(dt, 'timeline');
  const accent = accentColor || DEFAULT_ACCENT;

  const events = Array.isArray(dt.events) ? dt.events : [];
  if (!events.length) refuse('timeline: no events, so there is no sequence to draw');
  const tracks = Array.isArray(dt.tracks) && dt.tracks.length ? dt.tracks.slice() : ['record'];

  events.forEach((e, i) => {
    if (!e || typeof e.label !== 'string' || !e.label) refuse(`timeline: event ${i} has no label`);
    if (typeof e.t !== 'string' || !e.t) refuse(`timeline: event ${i} (${e.label}) has no time`);
    const tr = e.track === undefined ? tracks[0] : e.track;
    if (tracks.indexOf(tr) === -1) {
      refuse(`timeline: event ${i} (${e.label}) is on track ${JSON.stringify(tr)}, which is not one of ${JSON.stringify(tracks)}`);
    }
  });
  const gaps = Array.isArray(dt.gaps) ? dt.gaps : [];

  // ---- scale: real clock time when every string parses, otherwise authored order ----
  const parsed = events.map((e) => parseClock(e.t));
  const gapEnds = [];
  gaps.forEach((g) => { gapEnds.push(parseClock(g.from), parseClock(g.to)); });
  const boundsOk = (dt.start === undefined || parseClock(dt.start) !== null)
    && (dt.end === undefined || parseClock(dt.end) !== null);
  const timeMode = parsed.every((v) => v !== null) && gapEnds.every((v) => v !== null) && boundsOk;

  if (timeMode) {
    // Monotonicity is checked over the RECORD only. An `unverified` event is by definition one whose
    // time is disputed -- "maybe 7:30" sitting among entries at 7:40 and 7:44 is the whole reason the
    // figure exists -- so requiring it to fall in order would refuse exactly the timelines this
    // program was built to draw. The verified spine must still run forwards, which is what catches
    // the real defect here: 12-hour and 24-hour notation mixed in one table.
    let prevI = -1;
    for (let i = 0; i < parsed.length; i++) {
      if (events[i].kind === 'unverified') continue;
      if (prevI !== -1 && parsed[i] < parsed[prevI]) {
        refuse(`timeline: "${events[i].t}" is authored after "${events[prevI].t}" but reads as earlier; `
          + 'mixed 12-hour and 24-hour notation is the usual cause, and a scrambled axis would misstate '
          + 'the sequence. If the time is genuinely disputed, mark the event kind "unverified".');
      }
      prevI = i;
    }
  }

  const trackLabelW = tracks.reduce((m, t) => Math.max(m, estimateTextWidth(t, NOTE_FONT)), 0);
  const AX_L = PAD + Math.ceil(trackLabelW) + 16;
  const AX_R = VB_W - PAD;

  let xOf;
  if (timeMode) {
    const all = parsed.concat(gapEnds);
    if (dt.start !== undefined) all.push(parseClock(dt.start));
    if (dt.end !== undefined) all.push(parseClock(dt.end));
    const lo = Math.min.apply(null, all), hi = Math.max.apply(null, all);
    const span = hi - lo;
    xOf = (v) => (span === 0 ? (AX_L + AX_R) / 2 : AX_L + ((v - lo) / span) * (AX_R - AX_L));
  } else {
    const n = events.length;
    const byTime = new Map();
    events.forEach((e, i) => { if (!byTime.has(e.t)) byTime.set(e.t, i); });
    xOf = (v) => (n === 1 ? (AX_L + AX_R) / 2 : AX_L + (v / (n - 1)) * (AX_R - AX_L));
    gaps.forEach((g, gi) => {
      if (!byTime.has(g.from) || !byTime.has(g.to)) {
        refuse(`timeline: gap ${gi} runs ${JSON.stringify(g.from)} to ${JSON.stringify(g.to)}, `
          + 'but this timeline is not on a clock scale, so a gap must name two event times exactly');
      }
    });
    xOf.byTime = byTime;
  }
  const posOf = timeMode
    ? (i) => xOf(parsed[i])
    : (i) => xOf(i);
  const posOfTime = timeMode
    ? (s) => xOf(parseClock(s))
    : (s) => xOf(xOf.byTime.get(s));

  const out = head(dt.title);

  // The bounds get their own row well above the lanes. Drawn any lower they collide with the event
  // numbers, and in ordinal mode the first event sits at exactly AX_L, so "Monday" and the "1" under
  // it were printed on top of each other.
  if (dt.start !== undefined || dt.end !== undefined) {
    if (dt.start !== undefined) out.push(text(AX_L, 74, TICK_FONT, dt.start, { opacity: '0.82' }));
    if (dt.end !== undefined) out.push(text(AX_R, 74, TICK_FONT, dt.end, { anchor: 'end', opacity: '0.82' }));
  }

  const laneTop = 128;
  const laneStep = 46;
  const laneY = (k) => laneTop + k * laneStep;
  const laneBottom = laneY(tracks.length - 1) + 22;

  // Gap bands first, so markers and rules draw over them.
  gaps.forEach((g) => {
    const gx1 = posOfTime(g.from), gx2 = posOfTime(g.to);
    const x = Math.min(gx1, gx2), w = Math.max(2, Math.abs(gx2 - gx1));
    hatchBand(x, laneTop - 20, w, laneBottom - laneTop + 26, g.label).forEach((s) => out.push(s));
  });

  tracks.forEach((tr, k) => {
    const y = laneY(k);
    out.push(text(PAD, y + 6, NOTE_FONT, tr, { opacity: '0.82' }));
    out.push(line(AX_L, hp(y), AX_R, hp(y), RULE, 1));
  });

  // Marker numbers are placed in TWO PASSES, because two events close together in time put their
  // numbers on top of each other: a disputed "maybe 7:30" beside a recorded 7:40 printed as an
  // unreadable "4?3". Each lane is walked in x order and a number that would overlap the previous
  // one is lifted to a second row ABOVE the first (never below, which would collide with the next
  // lane). If both rows are taken the figure is REFUSED by name rather than drawn illegibly.
  const NUM_ROWS = [-14, -32];
  const placed = [];
  const rowsByLane = new Map();
  events.forEach((e, i) => {
    const k = tracks.indexOf(e.track === undefined ? tracks[0] : e.track);
    const cx = posOf(i), cy = laneY(k);
    const unver = e.kind === 'unverified';
    const glyph = unver ? (i + 1) + '?' : String(i + 1);
    const halfW = estimateTextWidth(glyph, NOTE_FONT) / 2 + 3;
    if (!rowsByLane.has(k)) rowsByLane.set(k, [[], []]);
    const rows = rowsByLane.get(k);
    let row = -1;
    for (let r = 0; r < NUM_ROWS.length && row === -1; r++) {
      const clash = rows[r].some((iv) => cx - halfW < iv[1] && cx + halfW > iv[0]);
      if (!clash) row = r;
    }
    if (row === -1) {
      refuse(`timeline: the markers for "${e.label}" and its neighbours on track `
        + `${JSON.stringify(tracks[k])} are too close to number legibly; space the events or split the figure`);
    }
    rows[row].push([cx - halfW, cx + halfW]);
    placed.push({ e, i, cx, cy, unver, glyph, row });
  });

  const entries = [];
  placed.forEach((p) => {
    out.push(circle(p.cx, p.cy, 7, p.unver
      ? { stroke: accent, strokeWidth: 2, dash: '3 3', extra: 'data-kind="unverified"' }
      : { fill: accent }));
    out.push(text(p.cx, p.cy + NUM_ROWS[p.row], NOTE_FONT, p.glyph, { anchor: 'middle', fill: accent }));
    entries.push({ n: p.i + 1, lead: p.e.t, label: p.e.label, mark: p.unver ? 'unverified' : null });
  });

  // The caption names the WINDOW as well as what happened in it. Drawing only the label left the
  // gap's own from/to in the dataTable and nowhere in the picture: a reader saw a hatched band with
  // no times on it, and every byte-compare was green because the fixture came from this same
  // renderer. tests/figure-fidelity.js part 2 is what caught it.
  let cursor = laneBottom + 14;
  gaps.forEach((g) => {
    const bounded = (typeof g.from === 'string' && typeof g.to === 'string')
      ? `${g.from} to ${g.to}` : '';
    const caption = [bounded, g.label].filter(Boolean).join('  ');
    if (!caption) return;
    const gx1 = posOfTime(g.from), gx2 = posOfTime(g.to);
    const cx = (gx1 + gx2) / 2;
    const w = estimateTextWidth(caption, NOTE_FONT);
    const clamped = Math.min(VB_W - PAD - w / 2, Math.max(PAD + w / 2, cx));
    out.push(text(clamped, cursor + NOTE_FONT, NOTE_FONT, caption, { anchor: 'middle', opacity: '0.82' }));
    cursor += ROW_H;
  });

  const key = keyBlock(entries, cursor + 6, accent);
  key.out.forEach((s) => out.push(s));

  return finish(out);
}

