function renderFacsimile(dataTable, accentColor) {
  const dt = dataTable || {};
  requireType(dt, 'facsimile');
  const accent = accentColor || DEFAULT_ACCENT;

  const header = Array.isArray(dt.header) ? dt.header : [];
  const lines = Array.isArray(dt.lines) ? dt.lines : [];
  const columns = Array.isArray(dt.columns) ? dt.columns : [];
  if (!header.length && !lines.length && !columns.length) {
    refuse('facsimile: no header, no lines and no columns, so there is no document to draw');
  }

  const CX = 56, CY = 34, CW = VB_W - 2 * CX, CH = VB_H - CY - 30;
  const out = svgRootLines();
  out.push(rect(CX, CY, CW, CH, { fill: CARD_FILL, stroke: RULE, rx: 6 }));

  const innerX = CX + 22;
  const innerW = CW - 44;
  let y = CY + 16;

  if (dt.title) {
    y += TITLE_FONT;
    out.push(text(innerX, y, TITLE_FONT, dt.title));
    y += 12;
    out.push(line(innerX, hp(y), CX + CW - 22, hp(y), HEADER_STROKE, 1));
    y += 10;
  }

  if (header.length) {
    const labW = header.reduce((m, h) => Math.max(m, estimateTextWidth((h && h.label) || '', TICK_FONT)), 0);
    header.forEach((h, i) => {
      if (!h || typeof h.value !== 'string') refuse(`facsimile: header row ${i} has no value`);
      y += LABEL_FONT + 6;
      if (h.label) out.push(text(innerX, y, TICK_FONT, h.label, { opacity: '0.82' }));
      out.push(text(innerX + Math.ceil(labW) + 16, y, LABEL_FONT, h.value));
    });
    y += 12;
    out.push(line(innerX, hp(y), CX + CW - 22, hp(y), HEADER_STROKE, 1));
    y += 6;
  }

  lines.forEach((l, i) => {
    if (!l || typeof l !== 'object') refuse(`facsimile: line ${i} is not an object`);
    const em = l.emphasis;
    y += LABEL_FONT + 10;
    if (em === 'redact') {
      // A redaction draws a bar and NEVER text under it: nothing a reader could recover.
      out.push(rect(innerX, y - LABEL_FONT + 2, innerW * 0.62, LABEL_FONT + 2,
        { fill: REDACTION_FILL, extra: 'data-emphasis="redact"' }));
      return;
    }
    if (typeof l.text !== 'string' || !l.text) refuse(`facsimile: line ${i} has no text and is not a redaction`);
    // Step the size down before giving up, and REFUSE rather than truncate: a truncated line is one
    // tests/figure-fidelity.js can no longer find verbatim in the passage it was transcribed from.
    const room = innerW - 24;
    const font = estimateTextWidth(l.text, LABEL_FONT) <= room ? LABEL_FONT : TICK_FONT;
    if (estimateTextWidth(l.text, font) > room) {
      refuse(`facsimile: line ${i} "${l.text}" needs ${Math.ceil(estimateTextWidth(l.text, font))}px `
        + `but the card is ${Math.floor(room)}px wide; shorten the transcription`);
    }
    const t = { text: l.text };
    const w = estimateTextWidth(t.text, font);
    if (em === 'box') {
      out.push(rect(innerX - 8, y - font, w + 16, font + 12,
        { stroke: accent, strokeWidth: 2, rx: 3, extra: 'data-emphasis="box"' }));
    } else if (em === 'underline') {
      out.push(line(innerX, hp(y + 5), innerX + w, hp(y + 5), accent, 2, { extra: 'data-emphasis="underline"' }));
    } else {
      out.push(line(innerX, hp(y + 7), CX + CW - 22, hp(y + 7), RULE, 1));
    }
    out.push(text(innerX, y, font, t.text));
  });

  if (columns.length) {
    y += 18;
    const colW = innerW / columns.length;
    const cellW = colW - 14;
    const rowsN = columns.reduce((m, c) => Math.max(m, (c && Array.isArray(c.rows) ? c.rows.length : 0)), 0);
    const CELL_LINE_H = 22;

    // WRAP, NEVER TRUNCATE. A truncated cell is a label tests/figure-fidelity.js can no longer find
    // verbatim in the figure, which is the one thing this whole design exists to guarantee. Two lines
    // are allowed; a cell that still will not fit is REFUSED by name, so the author shortens the
    // transcription deliberately instead of the renderer doing it silently.
    const fitOrRefuse = (s, font, where) => {
      const lines_ = wrapToWidth(String(s), font, cellW, 2);
      lines_.forEach((ln) => {
        if (estimateTextWidth(ln, font) > cellW) {
          refuse(`facsimile: ${where} "${s}" needs ${Math.ceil(estimateTextWidth(ln, font))}px but the `
            + `column is ${Math.floor(cellW)}px; use fewer columns or a shorter transcription`);
        }
      });
      return lines_;
    };

    const heads = columns.map((c, ci) => {
      if (!c || typeof c.heading !== 'string') refuse(`facsimile: column ${ci} has no heading`);
      return fitOrRefuse(c.heading, LABEL_FONT, `column heading`);
    });
    const cells = [];
    for (let r = 0; r < rowsN; r++) {
      cells.push(columns.map((c) => {
        const v = (c.rows || [])[r];
        if (v === undefined || v === null || v === '') return null;
        return fitOrRefuse(v, TICK_FONT, 'cell');
      }));
    }
    const headH = Math.max.apply(null, heads.map((h) => h.length)) * CELL_LINE_H + 12;
    const rowH = cells.map((row) => Math.max(1, Math.max.apply(null,
      row.map((c) => (c ? c.length : 1)))) * CELL_LINE_H + 6);
    const needed = headH + rowH.reduce((a, b) => a + b, 0) + 10;
    if (y + needed > CY + CH - 10) {
      refuse(`facsimile: ${columns.length} columns of ${rowsN} rows need ${Math.ceil(needed)}px but only `
        + `${Math.floor(CY + CH - 10 - y)}px remain under the header; shorten the table or move it to its own figure`);
    }

    const tableBottom = y + needed;
    heads.forEach((h, ci) => {
      const cx = innerX + ci * colW;
      out.push(textLines(cx, y + LABEL_FONT, LABEL_FONT, h, { lineH: CELL_LINE_H }));
      if (ci > 0) out.push(line(hp(cx - 8), y - 6, hp(cx - 8), tableBottom - 10, RULE, 1));
    });
    const headBase = y + headH;
    out.push(line(innerX, hp(headBase), CX + CW - 22, hp(headBase), HEADER_STROKE, 1));
    let ry = headBase;
    cells.forEach((row, r) => {
      row.forEach((cell, ci) => {
        if (!cell) return;
        const cx = innerX + ci * colW;
        out.push(textLines(cx, ry + TICK_FONT + 4, TICK_FONT, cell, { lineH: CELL_LINE_H }));
      });
      ry += rowH[r];
      if (r < cells.length - 1) out.push(line(innerX, hp(ry - 3), CX + CW - 22, hp(ry - 3), RULE, 1));
    });
    y = ry;
  }

  if (dt.stamp) {
    const sw = estimateTextWidth(dt.stamp, LABEL_FONT) + 26;
    const sx = CX + CW - sw - 34, sy = CY + CH - 58;
    const cx = sx + sw / 2, cy = sy + 20;
    out.push(`<g transform="rotate(-12 ${n2(cx)} ${n2(cy)})">`);
    out.push(rect(sx, sy, sw, 40, { stroke: STAMP_STROKE, strokeWidth: 2, rx: 4, extra: 'data-stamp="1"' }));
    out.push(text(cx, cy + 8, LABEL_FONT, dt.stamp, { anchor: 'middle', fill: accent }));
    out.push('</g>');
  }

  return finish(out);
}

