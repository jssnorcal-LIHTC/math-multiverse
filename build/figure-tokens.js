'use strict';
// figure-tokens.js -- the V1 design tokens and the deterministic string/number primitives shared by
// EVERY built-graphic generator in this repo.
//
// WHY THIS FILE EXISTS. build/figure-gen.js owned esc(), n2(), hp() and estimateTextWidth() as
// module-private functions, and assigns `module.exports` as its LAST statement (build/figure-gen.js
// :762, before only the require.main guard at :769). A second generator that required figure-gen.js
// for those helpers while figure-gen.js required it back for dispatch would receive a
// PARTIALLY-INITIALISED module -- an empty {} -- and every token would come back `undefined`. The
// failure would then be invisible forever, because the committed fixture SVGs would have been
// generated by that same broken code and would byte-match on every future run. Extracting the
// primitives here makes the dependency one-way and the cycle impossible:
//
//     figure-tokens.js   (requires nothing)
//        ^          ^
//        |          |
//   figure-gen.js  figure-gen-docs.js        figure-gen.js -> figure-gen-docs.js (dispatch only)
//
// DETERMINISM IS THE POINT. Every number written into an SVG string goes through n2(); every
// escape goes through esc(). No Date, no Math.random, no toLocaleString, no object-key iteration.
// Same inputs -> byte-identical output, every run, every platform. tests/figure-derive.js rests on
// that guarantee and tests/figure-docs.test.js asserts these values are twins of the ones
// build/figure-gen.js publishes, so the two can never drift apart unnoticed.

// ---- canvas geometry (twins of build/figure-gen.js:54, :73) ----
const VB_W = 800, VB_H = 450;

// Width-per-character estimate at font-size 1. Not a measurement: a deliberate, deterministic
// over-estimate that lets a generator size margins and wrap text without a font engine. Every
// consumer must use THIS number, because tests/figure-derive.js:126-131 builds its
// canvas-containment bounding boxes from the same formula.
const GLYPH_W = 0.6;

// The vertical half of that same bbox model (tests/figure-derive.js:126-131): a text run drawn at
// baseline y occupies y - ASCENT*fontSize .. y + DESCENT*fontSize.
const ASCENT = 0.8, DESCENT = 0.25;

// ---- the V1 colour tokens (twins of build/figure-gen.js:81-91) ----
// There are exactly five in the chart generator and no sixth colour literal anywhere in it.
const BG = '#0f1218';                        // background rect only
const INK = '#e8eef7';                       // all text; approx. 15.4:1 on BG
const GRID = 'rgba(255,255,255,0.12)';       // CHROME ONLY (axis border), never value-bearing
const PLOT_GRID = 'rgba(232,238,247,0.5)';   // value-bearing gridlines, approx. 4.7:1 on BG
const DEFAULT_ACCENT = '#7aa8ff';

// ---- six new tokens the document renderers need, each derived from the five above ----
// Contrast ratios are against BG and are stated so a later change cannot quietly drop below the
// level its role needs: text-adjacent marks stay above 4.5:1, pure chrome may sit lower.
const CARD_FILL = 'rgba(232,238,247,0.06)';    // the facsimile paper block: lifted off BG, not a fill
const RULE = 'rgba(232,238,247,0.28)';         // ruled lines and table rules; chrome, approx. 2.2:1
const HEADER_STROKE = 'rgba(232,238,247,0.5)'; // divider under a facsimile header block, approx. 4.7:1
const STAMP_STROKE = 'rgba(232,238,247,0.65)'; // the stamp outline, approx. 6.6:1
const HATCH_STROKE = 'rgba(232,238,247,0.35)'; // the timeline gap band's hatching, approx. 2.7:1
// A redaction must READ as a removal on a dark ground, so it is a solid light bar rather than the
// black bar a paper redaction uses, which would be invisible here. approx. 5.1:1.
const REDACTION_FILL = 'rgba(232,238,247,0.55)';

// ---- authored font sizes (twins of build/figure-gen.js:93) ----
// FONT_FLOOR is 18 and not the 15 the derive gate asserts, because 15 is a RENDERED floor: a static
// SVG in the lightbox renders at 0.9024x on the iPad 6's portrait viewport (94vw of 768 CSS px
// against an 800px native width), so an authored 15 arrives at 13.5px. 15 / 0.9024 = 16.62 is the
// true minimum and 18 is the smallest size the chart generator authors. See
// build/figure-gen.js:20-29 for the full derivation.
const TITLE_FONT = 26;   // a document's own title, the one line a reader orients on first
const LABEL_FONT = 22;   // primary labels
const TICK_FONT = 20;    // secondary labels and axis-equivalents
const NOTE_FONT = 18;    // footer notes only
const FONT_FLOOR = 18;

// ---- primitives, moved verbatim from build/figure-gen.js ----

// Fixed 2-decimal formatting with trailing zeros stripped. toFixed is spec-defined (not
// locale-dependent, unlike toLocaleString), so this is the same string on every platform for the
// same float. Used for BOTH pixel coordinates and printed value labels.
// Moved verbatim from build/figure-gen.js:113-120.
function n2(x) {
  let s = (Math.round(x * 100) / 100).toFixed(2);
  if (s.indexOf('.') !== -1) s = s.replace(/0+$/, '').replace(/\.$/, '');
  return s === '' || s === '-0' ? '0' : s;
}

// Moved verbatim from build/figure-gen.js:122-124. NOTE it does NOT escape the apostrophe, so every
// generator built on it must emit DOUBLE-quoted attributes only. tests/figure-docs.test.js pins that
// with a fixture label carrying an apostrophe.
function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// Half-pixel snap for STROKED CHROME coordinates only (gridlines, rules, axes, hatching): a 1px
// stroke centred on an integer coordinate straddles two device pixel rows and blurs; offsetting by
// 0.5 lands it on exactly one row. Never applied to geometry that must stay proportional to data.
// Moved verbatim from build/figure-gen.js:126-132.
function hp(v) {
  return Math.round(v) + 0.5;
}

// Moved verbatim from build/figure-gen.js:291-293.
function estimateTextWidth(text, fontSize) {
  return String(text).length * GLYPH_W * fontSize;
}

// A generator REFUSES what it cannot draw truthfully rather than drawing something misleading.
// Same discipline as build/figure-gen.js:134-140.
function refuse(reason) {
  throw new Error(reason);
}

// ---- new primitives the document renderers need ----

// Greedy word wrap against the SAME width estimate everything else uses. A single word wider than
// maxWidth gets its own line rather than being split mid-word: splitting a transcribed label would
// break the verbatim string tests/figure-fidelity.js looks for.
function wrapToWidth(text, fontSize, maxWidth, maxLines) {
  const words = String(text).split(/\s+/).filter(Boolean);
  if (!words.length) return [''];
  const lines = [];
  let cur = words[0];
  for (let i = 1; i < words.length; i++) {
    const next = cur + ' ' + words[i];
    if (estimateTextWidth(next, fontSize) <= maxWidth) { cur = next; }
    else { lines.push(cur); cur = words[i]; }
  }
  lines.push(cur);
  if (typeof maxLines === 'number' && lines.length > maxLines) {
    const kept = lines.slice(0, maxLines);
    // Fold everything that did not fit into the last kept line and let the caller truncate it, so
    // the overflow is visible as an ellipsis rather than silently deleted.
    kept[maxLines - 1] = kept[maxLines - 1] + ' ' + lines.slice(maxLines).join(' ');
    return kept;
  }
  return lines;
}

// Returns the flag as a VALUE rather than a side effect, so tests/figure-fidelity.js can accept a
// DECLARED truncation as the reason a transcribed label is not present in the SVG verbatim, and
// print the truncation WARNING the plan calls for, without re-measuring anything.
function truncateToWidth(text, fontSize, maxWidth) {
  const s = String(text);
  if (estimateTextWidth(s, fontSize) <= maxWidth) return { text: s, truncated: false };
  const ell = '…';
  const room = maxWidth - estimateTextWidth(ell, fontSize);
  if (room <= 0) return { text: ell, truncated: true };
  const keep = Math.max(0, Math.floor(room / (GLYPH_W * fontSize)));
  return { text: s.slice(0, keep).replace(/\s+$/, '') + ell, truncated: true };
}

// The SVG root, emitted byte-identically by every generator in this repo.
// width AND height are mandatory alongside viewBox and are NOT redundant: the reveal card sizes its
// image with `.mv-rv-img { height: 100%; width: auto }` inside a fixed 230px frame
// (engine/engine.css:266-268), and a viewBox-only SVG in an <img> falls back to the 300x150 default
// intrinsic size and renders distorted there.
function svgRootLines() {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${VB_W}" height="${VB_H}" viewBox="0 0 ${VB_W} ${VB_H}" role="img">`,
    `<rect x="0" y="0" width="${VB_W}" height="${VB_H}" fill="${BG}" />`,
  ];
}

module.exports = {
  VB_W, VB_H, GLYPH_W, ASCENT, DESCENT,
  BG, INK, GRID, PLOT_GRID, DEFAULT_ACCENT,
  CARD_FILL, RULE, HEADER_STROKE, STAMP_STROKE, HATCH_STROKE, REDACTION_FILL,
  TITLE_FONT, LABEL_FONT, TICK_FONT, NOTE_FONT, FONT_FLOOR,
  n2, esc, hp, estimateTextWidth, refuse, wrapToWidth, truncateToWidth, svgRootLines,
};
