'use strict';
// topic-index-gen.js -- generate the shell's TOPIC_INDEX block.
//
//   node build/topic-index-gen.js            (rewrites the block in Math-Multiverse.html)
//   node build/topic-index-gen.js --check    (exit 1 if the committed block is stale)
//
// TOPIC_INDEX maps every topic the six math modules actually EMIT to the module, grade and level
// that emits it most reliably. Today's Mission uses it to turn "this lesson needs dec-write-word"
// into "play F1 Apex Decimals, Grade 5, Level 1".
//
// WHY IT IS A STATIC MAP IN THE SHELL. Constraint 2: the six math IIFEs are never edited. Their
// generators are private to each closure and init(host, levelIndex, {onComplete, onExit}) exposes
// no per-question hook, so the shell cannot ask a module for one question of a given topic. What
// it CAN do is start the level whose dispatch emits that topic, which is exact wherever that
// level emits a single topic -- 43 of the 83 topics, as measured -- and approximate where the
// level mixes. The `share` field carries that honestly, and the mission says "mostly" rather
// than pretending. The generated block's own header prints the current split on every run.
//
// A drawTopic() method on each module would be more precise and is exactly the IIFE edit the
// constraint forbids, which is why the precision is bought with a measurement instead.
//
// Constraint 13: editing this file and running it happen in the same turn, and verification reads
// the final artifact. tests/mission.js re-measures and fails if the committed block has drifted.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const HTML = path.join(ROOT, 'Math-Multiverse.html');
const { loadModules, buildDrivers } = require(path.join(ROOT, 'tests', 'extract.js'));
const { seededMath, fnv, driverId } = require(path.join(ROOT, 'tests', 'gate-common.js'));

const BEGIN = '// <<< TOPIC_INDEX GENERATED BY build/topic-index-gen.js -- DO NOT EDIT BY HAND';
const END = '// >>> TOPIC_INDEX END';

const N = parseInt(process.env.TOPIC_INDEX_N || '2000', 10);
// Fixed seed. The shares below are sampled, so an unseeded run produces a slightly different
// number every time and the generated block could never be byte-stable -- which would make
// --check meaningless as a staleness gate. Same discipline tests/freshness-sim.js uses: each
// driver runs under its OWN derived Math, mulberry32(SEED ^ fnv(driverId)), so one driver's draw
// sequence can never move another's measured share.
const SEED = parseInt(process.env.TOPIC_INDEX_SEED || '20260822', 10);

// Sampled in two halves, like tests/validate-curriculum.js: if the second half turns up a topic
// the first half missed, the sample was too small and every share below is unreliable.
function measure(nPerDriver) {
  // extraGlobals: {} makes every driver.sandbox reachable so its Math can be reassigned per driver.
  const drivers = buildDrivers(loadModules(), { extraGlobals: {} });
  if (drivers.length !== 72) throw new Error('topic-index-gen: expected 72 drivers, got ' + drivers.length);
  const half = Math.max(50, Math.floor(nPerDriver / 2));
  const firstHalf = new Set();
  const sites = new Map();      // topic -> [{moduleId, grade, levelIndex, count, draws}]
  for (const d of drivers) {
    d.sandbox.Math = seededMath(SEED ^ fnv(driverId(d)));
    const counts = new Map();
    let draws = 0;
    for (let i = 0; i < half * 2; i++) {
      let q;
      try { q = d.make(); } catch (e) { continue; }
      draws++;
      const t = q && typeof q.topic === 'string' && q.topic ? q.topic : null;
      if (!t) continue;
      counts.set(t, (counts.get(t) || 0) + 1);
      if (i < half) firstHalf.add(t);
    }
    for (const [t, c] of counts) {
      if (!sites.has(t)) sites.set(t, []);
      sites.get(t).push({
        moduleId: d.moduleId, grade: d.grade, levelIndex: d.levelIndex,
        levelName: d.levelName || null, count: c, draws,
      });
    }
  }
  const all = new Set(sites.keys());
  const late = [...all].filter((t) => !firstHalf.has(t)).sort();
  if (late.length) {
    throw new Error(`topic-index-gen: the second sampling half found ${late.length} topic(s) the first `
      + `half missed (${late.join(', ')}); N=${nPerDriver} is too small for the shares to be trusted`);
  }
  if (!all.size) throw new Error('topic-index-gen: zero topics emitted -- extraction is broken');
  return { sites, drivers: drivers.length };
}

function build() {
  const { sites, drivers } = measure(N);
  const index = {};
  const stats = { exact: 0, mixed: 0, total: 0 };
  for (const topic of [...sites.keys()].sort()) {
    // Best site: the level where this topic is the largest share of the draws. Ties break toward
    // the lower grade, then the earlier level, so the choice is deterministic run to run.
    const ranked = sites.get(topic).slice().sort((a, b) => (
      (b.count / b.draws) - (a.count / a.draws)
      || a.grade - b.grade
      || a.levelIndex - b.levelIndex
      || a.moduleId.localeCompare(b.moduleId)
    ));
    const best = ranked[0];
    const share = +(best.count / best.draws).toFixed(3);
    index[topic] = {
      m: best.moduleId, g: best.grade, l: best.levelIndex,
      share, sites: ranked.length, name: best.levelName,
    };
    stats.total++;
    if (share >= 0.99) stats.exact++; else stats.mixed++;
  }

  const lines = [];
  lines.push(BEGIN);
  lines.push(`// ${stats.total} emitted topics, measured across ${drivers} real driver sites at N=${N} per site,`);
  lines.push(`// under a fixed seed (${SEED}) derived per driver, so the block is byte-stable and --check means something.`);
  lines.push(`// ${stats.exact} land on a level that emits ONLY that topic; ${stats.mixed} land on a mixed level and`);
  lines.push('// carry the measured share, which is what lets the mission say "mostly" instead of pretending.');
  lines.push('// m = module id, g = grade, l = level index, share = fraction of that level\'s draws,');
  lines.push('// sites = how many levels emit it at all, name = that level\'s name.');
  lines.push('const TOPIC_INDEX = {');
  for (const topic of Object.keys(index)) {
    const e = index[topic];
    lines.push(`  '${topic}': { m: '${e.m}', g: ${e.g}, l: ${e.l}, share: ${e.share}, sites: ${e.sites}, name: ${JSON.stringify(e.name)} },`);
  }
  lines.push('};');
  lines.push(END);
  return { block: lines.join('\n'), stats, index };
}

function readCommitted(html) {
  const i = html.indexOf(BEGIN);
  if (i < 0) return null;
  const j = html.indexOf(END, i);
  if (j < 0) return null;
  return html.slice(i, j + END.length);
}

// Line endings are NOT part of what this gate measures. .gitattributes normalises this file, so a
// fresh checkout on Windows hands back CRLF while build() always joins with LF: comparing the two
// raw reported STALE on a block that was byte-identical line for line. Measured 26-0822, after a
// checkout of main, with a zero-line diff and a failing --check. Both sides are normalised for the
// comparison, and a rewrite matches whatever the file already uses so this file's endings stay
// uniform.
const CRLF = '\r\n';
const LF = '\n';
const norm = (t) => String(t).split(CRLF).join(LF);
const matchEol = (block, html) => (html.indexOf(CRLF) >= 0 ? block.split(LF).join(CRLF) : block);

const { block, stats } = build();
const html = fs.readFileSync(HTML, 'utf8');
const committed = readCommitted(html);
const checkOnly = process.argv.includes('--check');

if (checkOnly) {
  if (committed == null) { console.error('topic-index-gen --check: no TOPIC_INDEX block found in the shell'); process.exit(1); }
  if (norm(committed) !== norm(block)) {
    console.error('topic-index-gen --check: the committed TOPIC_INDEX block is STALE.');
    console.error('  Run: node build/topic-index-gen.js');
    process.exit(1);
  }
  console.log(`topic-index-gen --check: the committed block matches a fresh measurement (${stats.total} topics).`);
  process.exit(0);
}

if (committed == null) {
  console.error('topic-index-gen: no TOPIC_INDEX markers in the shell. Add:\n  ' + BEGIN + '\n  const TOPIC_INDEX = {};\n  ' + END);
  process.exit(1);
}
fs.writeFileSync(HTML, html.replace(committed, matchEol(block, html)));
console.log(`wrote TOPIC_INDEX into Math-Multiverse.html`);
console.log(`  ${stats.total} topics: ${stats.exact} exact (a level emitting only that topic), ${stats.mixed} on a mixed level`);
