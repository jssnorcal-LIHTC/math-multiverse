let failures = 0;
function check(name, fn) {
  try { fn(); console.log('  ok   ' + name); }
  catch (e) { failures++; console.log('  FAIL ' + name + ': ' + e.message); }
}

function readFixture(base) {
  return JSON.parse(fs.readFileSync(path.join(FIX, base + '.json'), 'utf8'));
}
function readExpected(base) {
  // Committed with LF; a Windows checkout may hand back CRLF. Compare on LF, as
  // tests/figure-reconcile.js already does for the polygon SVGs.
  return fs.readFileSync(path.join(FIX, base + '.svg'), 'utf8').split('\r\n').join('\n');
}

