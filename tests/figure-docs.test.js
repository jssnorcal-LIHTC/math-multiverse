// The AUTHORED font floor. figure-gen.js sizes text for the lightbox, where the worst case is the
// iPad 6 portrait viewport: 94vw of 768 CSS px = 721.92px against an 800px native width, i.e.
// 0.9024x, so an authored size must clear 15 / 0.9024 = 16.62px to render at the 15px floor. Its
// own smallest authored size is NOTE_FONT = 18. These renderers may not go below it.
const FONT_FLOOR = 18;

// Pull every text run out of an SVG string with the attributes needed to bound it horizontally.
function textRuns(svg) {
  const runs = [];
  // The attribute run is CAPTURED here; textContents() below deliberately does not capture it.
  const re = /<text\b([^>]*)>([\s\S]*?)<\/text>/g;
  let m;
  while ((m = re.exec(svg)) !== null) {
    const attrs = m[1];
    const inner = m[2];
    // Anchored on a word boundary: an unanchored /y="([^"]*)"/ also matches the dy="" of a tspan,
    // which silently read every wrapped label's baseline as 0 and put it above the canvas.
    const get = (k) => {
      const a = new RegExp('(?:^|\\s)' + k + '="([^"]*)"').exec(attrs);
      return a ? a[1] : null;
    };
    const spans = [];
    let spanDy = 0;
    const spanRe = /<tspan\b([^>]*)>([\s\S]*?)<\/tspan>/g;
    let s;
    while ((s = spanRe.exec(inner)) !== null) {
      const sAttrs = s[1];
      const sGet = (k) => {
        const a = new RegExp('(?:^|\\s)' + k + '="([^"]*)"').exec(sAttrs);
        return a ? a[1] : null;
      };
      spanDy += sGet('dy') !== null ? parseFloat(sGet('dy')) : 0;
      spans.push({
        x: sGet('x') !== null ? parseFloat(sGet('x')) : (get('x') !== null ? parseFloat(get('x')) : 0),
        y: (get('y') !== null ? parseFloat(get('y')) : 0) + spanDy,
        fontSize: parseFloat(sGet('font-size') || get('font-size') || '0'),
        anchor: sGet('text-anchor') || get('text-anchor') || 'start',
        text: s[2],
      });
    }
    if (spans.length) { runs.push.apply(runs, spans); continue; }
    runs.push({
      x: get('x') !== null ? parseFloat(get('x')) : 0,
      y: get('y') !== null ? parseFloat(get('y')) : 0,
      fontSize: parseFloat(get('font-size') || '0'),
      anchor: get('text-anchor') || 'start',
      text: inner,
    });
  }
  return runs;
}

// Undo the four entities esc() writes, so a width estimate counts CHARACTERS a reader sees rather
// than the five of "&amp;". Overestimating width would make this check fire on figures that are
// actually fine, which is how a real gate gets disabled.
function unesc(s) {
  return String(s).replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&amp;/g, '&');
}

// The SAME estimator build/figure-gen.js uses for its own left margin (estimateTextWidth), rebuilt
// from the GLYPH_W constant it exports so the two can never disagree about how wide a label is.
function estWidth(text, fontSize) {
  return unesc(text).length * GLYPH_W * fontSize;
}

// The collapsed text content of each <text> element, tspans folded in. THIS is the level a fidelity
// check reads at, and the reason the renderers wrap with <tspan> inside one <text> rather than
// emitting one <text> per line: a label wrapped across two tspans is still that label, while a label
// split across two <text> elements does not exist in the document as a whole string at all.
function textContents(svg) {
  const out = [];
  const re = /<text\b[^>]*>([\s\S]*?)<\/text>/g;
  let m;
  while ((m = re.exec(svg)) !== null) {
    out.push(unesc(m[1].replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim());
  }
  return out;
}

function horizontalExtent(run) {
  const w = estWidth(run.text, run.fontSize);
  if (run.anchor === 'middle') return [run.x - w / 2, run.x + w / 2];
  if (run.anchor === 'end') return [run.x - w, run.x];
  return [run.x, run.x + w];
}

// ---------------------------------------------------------------------------
// 0. CONTROLS ON THIS FILE'S OWN MACHINERY.
// The canvas-containment and font-floor checks below are only worth their runtime if the parser
// feeding them actually reads the attributes it claims to. It did not, once: an attribute regex
// written as '(?:^|\s)' in a JS string literal compiles as '(?:^|s)', which matched nothing, so
// every baseline read as 0, the geometry check silently stopped measuring, and the suite went
// green BY GOING BLIND. These four controls fail if that happens again.
// ---------------------------------------------------------------------------
check('CONTROL: the parser actually reads x, y, font-size and text-anchor off a real element', () => {
  const runs = textRuns('<text x="40" y="44" font-size="26" fill="#e8eef7" text-anchor="middle">hi</text>');
  assert.strictEqual(runs.length, 1);
  assert.strictEqual(runs[0].x, 40, 'x was not read');
  assert.strictEqual(runs[0].y, 44, 'y was not read (an unanchored regex also matches dy=)');
  assert.strictEqual(runs[0].fontSize, 26, 'font-size was not read');
  assert.strictEqual(runs[0].anchor, 'middle', 'text-anchor was not read');
  assert.strictEqual(runs[0].text, 'hi');
});

check('CONTROL: a tspan baseline accumulates dy rather than reading dy as y', () => {
  const runs = textRuns('<text x="10" y="100" font-size="20" fill="#fff">'
    + '<tspan x="10" dy="0">one</tspan> <tspan x="10" dy="22">two</tspan></text>');
  assert.strictEqual(runs.length, 2);
  assert.strictEqual(runs[0].y, 100, 'first tspan should sit on the parent baseline');
  assert.strictEqual(runs[1].y, 122, 'second tspan should sit one line down, not at dy');
});

check('NEGATIVE CONTROL: text pushed off the canvas IS detected (the geometry check is armed)', () => {
  const off = '<text x="780" y="44" font-size="22" fill="#fff">a label far too wide to fit here</text>';
  const runs = textRuns(off);
  const ext = horizontalExtent(runs[0]);
  assert.ok(ext[1] > VB_W, 'a label running off the right edge was not measured as overflowing');
  const above = textRuns('<text x="40" y="4" font-size="22" fill="#fff">high</text>')[0];
  assert.ok(above.y - 0.8 * above.fontSize < 0, 'a label above the top edge was not measured as overflowing');
});

check('NEGATIVE CONTROL: a sub-floor font size IS detected', () => {
  const sizes = ('<text font-size="12">x</text>'.match(/font-size="([0-9.]+)"/g) || [])
    .map((s) => parseFloat(/"([0-9.]+)"/.exec(s)[1]));
  assert.deepStrictEqual(sizes.filter((s) => s < FONT_FLOOR), [12],
    'the font-floor scan does not actually find an undersized font');
});

