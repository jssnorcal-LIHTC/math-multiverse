'use strict';
// figure-docs.test.js -- unit gate for the four DOCUMENT renderers in build/figure-gen-docs.js
// (timeline, facsimile, schematic, route), the renderers that let the three ELA reading packs
// carry built graphics generated from a committed dataTable.
//
// WHY BYTE-COMPARE IS NOT ENOUGH, AND WHAT ELSE IS HERE. tests/figure-derive.js proves
// REPRODUCIBILITY: it regenerates a figure from its own dataTable and compares bytes, so both
// sides come from the same generator and a bug IN the generator reproduces perfectly. The
// committed fixture .svg files below have the same blindness -- they were generated BY these
// renderers. That is exactly the 26-0822 histogram defect (a byte-compare cannot see a defect in
// the renderer, because the renderer made both sides), and two of the four defects that shipped
// that day were green in every gate. So this file carries three families of check that do NOT
// come from the generator:
//   1. STRUCTURAL invariants read out of the emitted SVG (viewBox, no <script>, no SMIL, no remote
//      href) -- properties the renderer could get wrong and a byte-compare would happily freeze.
//   2. GEOMETRY measured against the canvas: every <text> run's estimated extent must lie inside
//      the 800x450 viewBox, using the SAME width estimator figure-gen.js uses for its own margins.
//      A label past the edge is a data-truth defect, not a cosmetic one: the figure then displays
//      less than its dataTable says.
//   3. SEMANTIC invariants the plan makes requirements: the authored font floor, a redacted line
//      that draws a bar and NEVER text under it, an unverified event drawn dashed and marked, a
//      gap drawn as a band. Each is a thing a reader would be misled by if it silently stopped
//      working, and none is visible to a byte-compare.
// The fixture PNGs were also looked at by eye before the .svg files were committed as expected
// output (plan W0.1 step 3). A fixture nobody looked at is the 26-0822 histogram again.

