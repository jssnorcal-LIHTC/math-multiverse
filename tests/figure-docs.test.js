// 6. Geometry: no label may leave the canvas (a plan W0.1 requirement, not taste)
// ---------------------------------------------------------------------------
CASES.forEach((c) => {
  check(c.base + ': every text run lies inside the 800x450 canvas', () => {
    const svg = docs[c.fn](readFixture(c.base), ACCENT);
    const runs = textRuns(svg);
    assert.ok(runs.length > 0, 'no text at all was drawn, so this check is vacuous');
    const bad = [];
    runs.forEach((r) => {
      const ext = horizontalExtent(r);
      if (ext[0] < 0 || ext[1] > VB_W) {
        bad.push('"' + r.text + '" spans ' + ext[0].toFixed(1) + '..' + ext[1].toFixed(1));
      }
      // The SAME ascent/descent model tests/figure-derive.js:126-131 builds its bounding boxes
      // from, so a figure that passes here cannot fail the derive gate's containment check.
      const top = r.y - 0.8 * r.fontSize, bot = r.y + 0.25 * r.fontSize;
      if (top < 0 || bot > VB_H) {
        bad.push('"' + r.text + '" spans y ' + top.toFixed(1) + '..' + bot.toFixed(1));
      }
    });
    assert.deepStrictEqual(bad, [], 'text outside the canvas: ' + bad.join('; '));
  });
});

